// Script to generate placeholder icons
// Run: node scripts/generate-icons.js

const fs = require('fs');
const path = require('path');

// Simple 1x1 PNG for each icon (placeholder)
// Replace with real icons later
const pngHeader = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, // 1x1 pixel
  0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, // 8-bit RGB
  0xDE, 0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41, // IDAT chunk
  0x54, 0x08, 0xD7, 0x63, 0x90, 0xE0, 0x98, 0x02, // compressed data
  0x00, 0x00, 0x02, 0x01, 0x00, 0x05, 0x18, 0xCF,
  0xA4, 0xFE, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
  0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82, // IEND chunk
]);

const publicDir = path.join(__dirname, '..', 'public');

// Create placeholder PNG
fs.writeFileSync(path.join(publicDir, 'icon.png'), pngHeader);
console.log('Created public/icon.png (placeholder - replace with real 512x512 icon)');

